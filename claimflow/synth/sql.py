"""Write generated reference data and benefit history as a Postgres seed script.

Claims to be *submitted* are not seeded; they go through the intake API so the
whole pipeline gets exercised. Only prior, already-decided claims are seeded,
so annual-maximum calculations have history to work with.
"""

from __future__ import annotations

from datetime import date, datetime


def lit(v) -> str:
    """Render a Python value as a SQL literal."""
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, (date, datetime)):
        return f"'{v.isoformat()}'"
    return "'" + str(v).replace("'", "''") + "'"


def insert(table: str, columns: list[str], rows: list[list]) -> str:
    if not rows:
        return ""
    values = ",\n".join("  (" + ", ".join(lit(v) for v in row) + ")" for row in rows)
    return f"INSERT INTO {table} ({', '.join(columns)}) VALUES\n{values};\n\n"


def seed_script(plans, providers: list[dict], members: list[dict], history: list[dict]) -> str:
    out = ["-- Generated by scripts/generate_data.py. Synthetic data only.\n",
           "SET search_path TO claimflow;\nBEGIN;\n\n"]

    out.append(insert("plans", ["plan_id", "name", "sponsor"],
                      [[p.plan_id, p.name, p.sponsor] for p in plans]))
    out.append(insert(
        "coverage_rules",
        ["plan_id", "category", "coinsurance_pct", "per_visit_max_cents",
         "annual_max_cents", "requires_registered_provider"],
        [[p.plan_id, r.category, r.coinsurance_pct, r.per_visit_max_cents,
          r.annual_max_cents, r.requires_registered_provider] for p in plans for r in p.rules]))
    out.append(insert(
        "providers",
        ["provider_id", "clinic_name", "practitioner_name", "category",
         "registration_number", "is_registered", "address", "province"],
        [[p["provider_id"], p["clinic_name"], p["practitioner_name"], p["category"],
          p["registration_number"], p["is_registered"], p["address"], p["province"]]
         for p in providers]))
    out.append(insert(
        "members",
        ["member_id", "plan_id", "first_name", "last_name", "date_of_birth",
         "province", "coverage_start", "coverage_end"],
        [[m["member_id"], m["plan_id"], m["first_name"], m["last_name"], m["date_of_birth"],
          m["province"], m["coverage_start"], m["coverage_end"]] for m in members]))

    out.append(insert(
        "claims",
        ["claim_id", "member_id", "submitted_at", "channel", "status",
         "document_uri", "document_sha256"],
        [[h["claim_id"], h["member_id"], h["submitted_at"], "web", "paid",
          f"archive://history/{h['claim_id']}", h["document_sha256"]] for h in history]))
    out.append(insert(
        "claim_lines",
        ["claim_id", "provider_id", "category", "service_date", "amount_cents"],
        [[h["claim_id"], h["provider_id"], h["category"], h["service_date"], h["amount_cents"]]
         for h in history]))
    out.append(insert(
        "decisions",
        ["claim_id", "outcome", "payout_cents", "explanation", "decided_by", "rules_version"],
        [[h["claim_id"], "approve", h["payout_cents"], "Prior claim imported from history.",
          "system", "history-import"] for h in history]))

    out.append("COMMIT;\n")
    return "".join(out)
